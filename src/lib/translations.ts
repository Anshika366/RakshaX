export function getTranslation(lang: string, key: string, params?: Record<string, string | number>): string {
  const selectedLang = (translations[lang as SupportedLanguage] ? lang : 'en') as SupportedLanguage;
  let text = translations[selectedLang][key] || translations['en'][key] || key;
  if (params) {
    Object.keys(params).forEach(pKey => {
      text = text.replace(`{${pKey}}`, String(params[pKey]));
    });
  }
  return text;
}
